import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const output = new URL('../Research/2026-10-24-galactic-jets-hdr/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({channel:'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
page.on('console', msg=>{if(msg.type()==='error') errors.push(msg.text());});
const shot=async name=>page.screenshot({path:fileURLToPath(new URL(name+'.png',output))});
const set=async(label,value)=>page.getByLabel(label,{exact:true}).fill(String(value));
try {
 await page.goto('http://localhost:4189/?preset=galactic-rim'); await page.waitForTimeout(2200); await shot('galactic-rim');
 await page.getByText('Galactic Rim Nebula',{exact:true}).click();
 await set('Band thickness (deg)',18); await set('Center longitude (deg)',-60); await page.waitForTimeout(700); await shot('galactic-rim-thick-moved');
 await page.getByRole('button',{name:'PCG',exact:true}).click();
 await page.getByLabel('Type',{exact:true}).selectOption('anomaly');
 await page.getByLabel('Style',{exact:true}).selectOption('quasar');
 await set('Jet length',0.34); await set('Jet cone (deg)',12); await set('Plume warp',0.8); await set('Plume density',1.6); await set('Tip strength',3);
 await page.waitForTimeout(400);
 await page.locator('img.gen-preview').screenshot({path:fileURLToPath(new URL('quasar.png',output))});
 const core=await page.locator('img.gen-preview').getAttribute('src');
 await page.getByLabel('Show central object',{exact:true}).uncheck();
 await page.waitForTimeout(300);
 await page.locator('img.gen-preview').screenshot({path:fileURLToPath(new URL('quasar-plumes-only.png',output))});
 const plumes=await page.locator('img.gen-preview').getAttribute('src');
 if(core===plumes)throw Error('Core toggle did not change preview');
 await set('Tip strength',0); const noTip=await page.locator('img.gen-preview').getAttribute('src');
 if(noTip===plumes)throw Error('Tip controls did not change preview');
 await page.getByLabel('Style',{exact:true}).selectOption('black-hole-jets');
 await page.waitForTimeout(600);
 await page.locator('img.gen-preview').screenshot({path:fileURLToPath(new URL('black-hole-jets.png',output))});
 await page.getByRole('button',{name:'Bake to Sprites',exact:true}).click();
 await page.getByRole('button',{name:/Add .* to skybox/}).click();
 await page.getByRole('button',{name:'Layers',exact:true}).click();
 await page.getByLabel('Size',{exact:true}).fill('0.3');
 await page.waitForTimeout(600); await shot('placed-black-hole-jets');
 await page.goto('http://localhost:4189/?preset=galactic-rim'); await page.waitForTimeout(900);
 await page.getByText('Galactic Band Stars',{exact:true}).click();
 await page.getByRole('button',{name:'Add aligned band nebula',exact:true}).click();
 if(await page.getByLabel('Band tilt (deg)',{exact:true}).inputValue()!=='90') throw Error('Aligned nebula did not copy star tilt');
 await page.getByRole('button',{name:'Script',exact:true}).click();
 const saved=JSON.parse(await page.locator('textarea.script-text').inputValue());
 if(saved.layers.length!==4 || !saved.layers[3].bandEnabled || saved.layers[1].maskEnabled!==false) throw Error('Aligned band creation failed');
 if(errors.length)throw Error(errors.join('\n'));
 await writeFile(new URL('visual-results.json',output),JSON.stringify({errors,checks:['band thickness and center movement','quasar textured cone','core hidden','tip strength changed','black-hole jets baked, placed and resized']},null,2));
 console.log('Visual checks passed');
}finally{await browser.close();}
