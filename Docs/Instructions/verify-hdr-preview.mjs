import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const output = new URL('../Research/2026-10-25-hdr-preview/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
try {
  await page.goto('http://localhost:4189/?preset=nebula-jets'); await page.waitForTimeout(1800);
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  await page.getByLabel('Resolution', { exact: true }).selectOption('2048');
  await page.locator('#export-hdr').check();
  await page.getByRole('button', { name: 'Preview HDR smoothness', exact: true }).click();
  await page.getByRole('button', { name: 'Close preview', exact: true }).waitFor({ timeout: 120000 });
  await page.locator('.hdr-preview-native').waitFor({ timeout: 120000 });
  await page.getByRole('button', { name: 'Pick another preview area', exact: true }).click();
  const box = await page.locator('.viewport canvas').boundingBox();
  await page.getByRole('button', { name: 'Pick HDR preview area', exact: true }).click({ position: { x: box.width / 2 - 18, y: box.height * 0.28 } });
  await page.getByRole('button', { name: 'Close preview', exact: true }).waitFor({ timeout: 120000 });
  await page.locator('.hdr-preview-native').waitFor({ timeout: 120000 });
  const set = async (label, value) => page.getByLabel(label, { exact: true }).locator('..').locator('input[type=number]').fill(String(value));
  await set('Preview softness', 4);
  const raw = await page.locator('.hdr-preview-native').getAttribute('src');
  const soft = await page.locator('.hdr-preview-softened').getAttribute('src');
  if (raw === soft) throw Error('Softness preview did not change the native crop');
  await set('Exposure (EV)', -2);
  if (raw === await page.locator('.hdr-preview-native').getAttribute('src')) throw Error('Exposure did not affect display');
  await page.getByLabel('Pixel zoom', { exact: true }).selectOption('2');
  await page.screenshot({ path: fileURLToPath(new URL('hdr-smoothness-preview.png', output)) });
  await set('Preview softness', 0);
  if (await page.locator('.hdr-preview-native').getAttribute('src') !== await page.locator('.hdr-preview-softened').getAttribute('src')) throw Error('Zero softness did not retain native image');
  await page.getByRole('button', { name: 'Close preview', exact: true }).click();
  if (await page.getByLabel('HDR softness', { exact: true }).inputValue() !== '0') throw Error('Preview softness did not update export setting');
  await page.getByLabel('Resolution', { exact: true }).selectOption('16384');
  await page.getByLabel('HDR softness', { exact: true }).fill('4');
  await page.getByRole('button', { name: 'Preview HDR smoothness', exact: true }).click();
  await page.getByRole('button', { name: 'Close preview', exact: true }).waitFor({ timeout: 120000 });
  await page.locator('.hdr-preview-native').waitFor({ timeout: 120000 });
  await page.getByRole('button', { name: 'Pick another preview area', exact: true }).click();
  await page.getByRole('button', { name: 'Pick HDR preview area', exact: true }).click({ position: { x: box.width / 2 - 18, y: box.height * 0.28 } });
  await page.getByRole('button', { name: 'Close preview', exact: true }).waitFor({ timeout: 120000 });
  await page.locator('.hdr-preview-native').waitFor({ timeout: 120000 });
  await page.screenshot({ path: fileURLToPath(new URL('hdr-smoothness-preview-16k.png', output)) });
  await page.getByRole('button', { name: 'Close preview', exact: true }).click();
  await page.getByRole('button', { name: 'Preview HDR smoothness', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => window.__preview.activeTileSources === 0);
  if (await page.getByRole('dialog').count()) throw Error('Escape did not cancel preview');
  if (errors.length) throw Error(errors.join('\n'));
  await writeFile(new URL('results.json', output), JSON.stringify({ errors, checks: ['native export-resolution crop', 'viewport area picking', 'softness comparison', 'preview exposure', 'pixel zoom', 'zero-softness equality', 'softness changes actual export option', 'native 16K-face crop with matching filter radius', 'Escape cancellation releases renderer'] }, null, 2));
  console.log('HDR preview checks passed');
} finally { await browser.close(); }
