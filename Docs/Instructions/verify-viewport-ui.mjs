import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const output = new URL('../Research/2026-10-25-viewport-ui/', import.meta.url); await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1432, height: 900 }, acceptDownloads: true });
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('dialog', async d => { errors.push(d.message()); await d.dismiss(); });
  const shot = n => page.screenshot({ path: fileURLToPath(new URL(n + '.png', output)) });
  await page.goto('http://localhost:4189/?preset=smoke-clouds'); await page.waitForTimeout(1800);
  await page.getByLabel('Smoke density value', { exact: true }).fill('0.75'); await page.waitForTimeout(400);
  const fit = await page.getByLabel('Smoke density value', { exact: true }).evaluate(el => {
    const row = el.closest('.field-row'), rect = el.getBoundingClientRect(), panel = document.querySelector('.sidebar').getBoundingClientRect();
    return { width: rect.width, rowOverflow: row.scrollWidth - row.clientWidth, right: rect.right, panelRight: panel.right };
  });
  if (fit.width < 80 || fit.rowOverflow > 1 || fit.right > fit.panelRight) throw Error('Smoke numeric control still overflows');
  await shot('smoke-control-fit');
  if (await page.getByLabel('Hide layer', { exact: true }).count()) throw Error('Hide control remains in properties');
  const row = page.locator('.layer-list li').first();
  await row.getByRole('button', { name: 'Hide Oxygen cloud', exact: true }).click();
  if (!await row.getByRole('button', { name: 'Show Oxygen cloud', exact: true }).isVisible()) throw Error('Row visibility action is missing');
  await row.getByRole('button', { name: 'Show Oxygen cloud', exact: true }).click();
  await page.getByLabel('Field of view value', { exact: true }).fill('55');
  if (await page.evaluate(() => window.__preview.camera.fov) !== 55) throw Error('FOV field did not update camera');
  await page.getByLabel('Viewport projection', { exact: true }).selectOption('2d'); await page.waitForTimeout(1000); await shot('panorama-2d');
  const coords = await page.evaluate(() => {
    const r = document.querySelector('.viewport canvas').getBoundingClientRect();
    return window.__preview.lonLatAtClient(r.x + r.width / 2, r.y + r.height / 2);
  });
  if (Math.abs(coords.lonDeg) > 0.001 || Math.abs(coords.latDeg) > 0.001) throw Error('Flat panorama picking is incorrect');
  const canvas = await page.locator('.viewport canvas').boundingBox();
  await page.mouse.move(canvas.x + canvas.width / 2, canvas.y + canvas.height / 2); await page.mouse.down();
  await page.mouse.move(canvas.x + canvas.width / 2 + 50, canvas.y + canvas.height / 2 - 20, { steps: 5 }); await page.mouse.up();
  await page.getByRole('button', { name: 'Script', exact: true }).click();
  const moved = JSON.parse(await page.locator('textarea.script-text').inputValue());
  if (Math.abs(moved.layers[0].dirLonDeg) < 1) throw Error('2D cloud dragging did not commit');
  await page.getByRole('button', { name: 'Layers', exact: true }).click(); await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.getByLabel('Viewport projection', { exact: true }).selectOption('3d');
  if (await page.getByLabel('Field of view value', { exact: true }).inputValue() !== '55') throw Error('Projection change lost FOV');
  await page.getByRole('button', { name: 'HDR preview', exact: true }).click();
  await page.getByRole('button', { name: 'Close preview', exact: true }).waitFor({ timeout: 120000 });
  await page.locator('.hdr-preview-native').waitFor({ timeout: 120000 }); await shot('hdr-preview-discoverable');
  await page.getByRole('button', { name: 'Close preview', exact: true }).click();
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const saving = page.getByLabel('Memory-saving export', { exact: true });
  if (!await saving.isChecked() || !await saving.isDisabled()) throw Error('Unsafe legacy export is still selectable');
  await page.getByLabel('Resolution', { exact: true }).selectOption('512'); await page.locator('#export-faces').uncheck(); await page.locator('#export-png').check();
  await page.evaluate(() => { window.__savedTileSource = window.__preview.createTileSource; window.__preview.createTileSource = async () => { throw new RangeError('Array buffer allocation failed'); }; });
  await page.locator('.export-go').click();
  await page.getByRole('alert').filter({ hasText: 'Export failed (512px/face; PNG)' }).waitFor();
  if (!(await page.getByRole('alert').textContent()).includes('lower resolution')) throw Error('Allocation failure has no recovery guidance');
  await page.evaluate(() => { window.__preview.createTileSource = window.__savedTileSource; delete window.__savedTileSource; });
  const download = page.waitForEvent('download'); await page.locator('.export-go').click(); await (await download).saveAs(fileURLToPath(new URL('ui-export.png', output)));
  await page.waitForFunction(() => !document.querySelector('.export-panel'));
  await page.setViewportSize({ width: 370, height: 800 }); await page.waitForTimeout(300); await shot('narrow-controls');
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth); if (overflow) throw Error('Narrow viewport has horizontal page overflow');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  await page.locator('.export-go').scrollIntoViewIfNeeded();
  const go = await page.locator('.export-go').boundingBox();
  if (go.y < 0 || go.y + go.height > 800) throw Error('Export action is clipped on a narrow screen');
  await shot('narrow-export');
  if (errors.length) throw Error(errors.join('\n'));
  await writeFile(new URL('results.json', output), JSON.stringify({ errors, fit, coords, checks: ['numeric fit', 'row visibility', 'FOV', '2D projection and dragging', 'HDR discovery', 'bounded export', 'simulated allocation error guidance and retry', 'narrow layout', 'narrow export action reachable'] }, null, 2));
  console.log('Viewport UI and export checks passed');
} finally { await browser.close(); }
